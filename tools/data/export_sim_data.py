#!/usr/bin/env python3
"""Export the gameplay data the simulator needs into sim/data/gamedata.json.

Reads the typed JSON produced by build_json.py / build_cards.py
(extracted/data/json) and writes one compact file with:

* every global (flat), the Default and other battle timelines, tower scaling
  and the card power-level multiplier table;
* the standard tilemap and spawn groups (tower layouts);
* every character, building, projectile, area-effect object and buff, with
  purely visual/audio fields removed (art lives in the viewer's baked assets);
* every playable card (spells_characters/buildings/other) with its gameplay
  fields.

The repository is private, so this small decoded file may be committed under
sim/data/ (AGENTS.md). Regenerate it after changing the data tools:

    python3 -I tools/data/build_json.py && python3 -I tools/data/build_cards.py
    python3 -I tools/data/export_sim_data.py
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

# Field names that only drive visuals, sound, UI or meta-game. Anything not
# matched stays in the export, so new gameplay fields are never dropped silently.
VISUAL = re.compile(
    r"((?<!Area)Effect(?!Object)|Export|FileName|SWF|Shadow|Sound|^TID|Icon|Prestige|HealthBar|PrefabAsset|"
    r"UseAnimator|DeployBaseAnim|LoopingFilter|CrowdEffects|ShaderFX|StatsTags|ClientActions|"
    r"Highres|Placeholder|AutoChess|CustomAnimation|VisualLayer|HasRotationOnTimeline|"
    r"HideHealthbar|ShowHealthNumber|TrailEffect|Scale$|^Scale|AnimationsKeepLastFrame|"
    r"DontStopMoveAnim|TurretMovement|SkinType|CardPropertyTags|Stats$|UnlockArena|"
    r"PveDefenseType|Tribe|PrestigeCount|SortOrder|MarkEffect|FilterFile|FilterExportName|"
    r"AudioPitch|LoopMoveEffect|TargetEffectY|HasDamageVisualPivot|use360Frames|ExportName)"
)


def load(name: str):
    return json.loads((ROOT / "extracted/data/json" / f"{name}.json").read_text())


def strip(rec: dict) -> dict:
    out = {}
    for k, v in rec.items():
        if k == "_meta" or VISUAL.search(k):
            continue
        out[k] = v
    return out


def rows(table) -> list[dict]:
    if isinstance(table, dict) and "rows" in table:
        r = table["rows"]
        return list(r.values()) if isinstance(r, dict) else r
    if isinstance(table, dict):
        return list(table.values())
    return table


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=ROOT / "sim/data/gamedata.json")
    args = ap.parse_args()

    match_rules = load("match_rules")
    rarities = {r["Name"]: r for r in rows(load("rarities")) if isinstance(r, dict) and r.get("Name")}
    common = rarities["Common"]
    power = [100] + list(common["PowerLevelMultiplier"])

    tilemaps = load("tilemaps")
    tm = tilemaps["tilemap"]
    grid = [v or 0 for row in tm["grid"] for v in row]

    units: dict[str, dict] = {}
    for kind, table in (("character", "characters"), ("building", "buildings")):
        for name, rec in load(table).items():
            r = strip(rec)
            r["_kind"] = kind
            units[name] = r

    def table(name: str) -> dict:
        return {k: strip(v) for k, v in load(name).items()}

    texts: dict[str, str] = {}
    texts_path = ROOT / "extracted/data/raw/csv_client/texts.csv"
    if texts_path.exists():
        import csv
        with texts_path.open(encoding="utf-8", newline="") as f:
            for row in csv.reader(f):
                if len(row) > 1 and row[0].startswith("TID_"):
                    texts[row[0]] = row[1]

    cards: dict[str, dict] = {}
    for kind, name in (("troop", "spells_characters"), ("building", "spells_buildings"), ("spell", "spells_other")):
        for rec in rows(load(name)):
            if not isinstance(rec, dict) or not rec.get("Name"):
                continue
            r = strip(rec)
            r["_type"] = kind
            tid = rec.get("TID")
            if isinstance(tid, str) and tid in texts:
                r["_displayName"] = texts[tid]
            cards[rec["Name"]] = r

    out = {
        "_doc": "Generated by tools/data/export_sim_data.py from build 160402020. Distances in game units "
                "(1000 = 1 tile), times in ms, stats at card level 1 (scale with powerMultiplier).",
        "build": "160402020",
        "globals": load("globals_flat"),
        "timelines": match_rules["timelines"],
        "towerScaling": match_rules["tower_scaling"],
        "powerMultiplier": power,
        "rarities": {k: {"RelativeLevel": v.get("RelativeLevel", 0), "LevelCount": v.get("LevelCount"),
                         "TournamentLevelIndex": v.get("TournamentLevelIndex")} for k, v in rarities.items()},
        "tilemap": {"width": tm["width"], "height": tm["height"], "grid": grid},
        "spawnGroups": load("spawn_groups"),
        "units": units,
        "projectiles": table("projectiles"),
        "areaEffects": table("area_effect_objects"),
        "buffs": table("character_buffs"),
        "damageTypes": {k: {kk: vv for kk, vv in v.items() if kk != "_meta"} for k, v in load("damage_types").items()},
        "filters": {k: {kk: vv for kk, vv in v.items() if kk != "_meta"} for k, v in load("game_object_filters").items()},
        "cards": cards,
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(out, separators=(",", ":"), sort_keys=True))
    print(f"wrote {args.out} ({args.out.stat().st_size:,} bytes): {len(units)} units, "
          f"{len(out['projectiles'])} projectiles, {len(out['areaEffects'])} area effects, "
          f"{len(out['buffs'])} buffs, {len(cards)} cards")


if __name__ == "__main__":
    main()
