#!/usr/bin/env python3
"""Regenerate tools/audio/vorbis_setup.py (developer tool, not run by the bake).

FMOD's FSB5 Vorbis samples omit the three Vorbis header packets. Each sample stores the CRC32 of
the setup header the FMOD encoder used; the setup header itself is the one libvorbisenc builds for
(quality, channels, rate) (python-fsb5's lookup table, MIT). This script rebuilds those setup
packets with the system's libvorbisenc through the `fsb5` package, checks each against its CRC32,
asks libvorbis for every mode's block size, and writes the result as plain data so the bake
(tools/audio/fsb5_ogg.py) needs no native library.

  pip install fsb5            # plus libogg / libvorbis / libvorbisenc on the system
  python3 tools/audio/gen_vorbis_setup.py [crc32 ...]

Without arguments it scans game-files/asset-pack/assets/soundbanks/*.bank for the CRCs in use.
The output holds only libvorbis encoder configuration (no game content).
"""
from __future__ import annotations

import base64
import ctypes
import glob
import sys
import zlib
from pathlib import Path

import fsb5
from fsb5 import vorbis as fv
from fsb5.vorbis_headers import lookup

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).with_name("vorbis_setup.py")


def crcs_in_banks() -> set[int]:
    out: set[int] = set()
    for f in sorted(glob.glob(str(ROOT / "game-files/asset-pack/assets/soundbanks/*.bank"))):
        d = Path(f).read_bytes()
        i = d.find(b"FSB5")
        if i < 0:
            continue
        for s in fsb5.FSB5(d[i:]).samples:
            vd = s.metadata.get(fsb5.MetadataChunkType.VORBISDATA)
            if vd:
                out.add(vd.crc32)
    return out


def mode_blocksizes(quality: int, channels: int, rate: int, short: int, long: int, setup: bytes) -> list[int]:
    """Block size of every mode: feed libvorbis the three headers, then 1-byte audio packets."""
    info, comment = fv.VorbisInfo(), fv.VorbisComment()
    fv.vorbis.vorbis_synthesis_headerin(info, comment, fv.rebuild_id_header(channels, rate, short, long))
    fv.vorbis.vorbis_synthesis_headerin(info, comment, fv.rebuild_comment_header())
    fv.vorbis.vorbis_synthesis_headerin(info, comment, fv.rebuild_setup_header(setup))
    out: list[int] = []
    for mode in range(64):
        buf = ctypes.create_string_buffer(bytes([(mode << 1) & 0xFF, mode >> 7, 0, 0]), 4)
        pk = fv.OggPacket()
        pk.packet = ctypes.cast(buf, ctypes.POINTER(ctypes.c_char))
        pk.bytes = 4
        try:
            bs = fv.vorbis.vorbis_packet_blocksize(info, pk)
        except OSError:
            break
        if bs <= 0:
            break
        out.append(bs)
    # only ilog(modes - 1) bits are read, so larger probes alias: keep the smallest period
    p = 1
    while p < len(out) and any(out[i] != out[i % p] for i in range(len(out))):
        p *= 2
    return out[:p]


def main() -> None:
    crcs = {int(a) for a in sys.argv[1:]} or crcs_in_banks()
    rows = []
    for crc in sorted(crcs):
        quality, channels, rate = lookup[crc]
        short, long, setup = fv.get_header_info(quality, channels, rate)
        if zlib.crc32(setup) != crc:
            raise SystemExit(f"setup header for crc {crc} does not match (libvorbisenc version?)")
        modes = mode_blocksizes(quality, channels, rate, short, long, setup)
        rows.append((crc, channels, rate, short, long, modes, base64.b64encode(zlib.compress(setup, 9)).decode()))
        print(crc, quality, channels, rate, short, long, len(setup), "modes", modes)
    lines = [
        '"""Vorbis setup headers of the FMOD encoder settings used by the banks (generated by',
        "gen_vorbis_setup.py from libvorbisenc; encoder configuration only, no game content).",
        "crc32 -> (channels, rate, blocksize_short, blocksize_long, block size per mode, b64 zlib setup)",
        '"""',
        "SETUPS = {",
    ]
    for crc, ch, rate, s, l, modes, b64 in rows:
        lines.append(f"    {crc}: ({ch}, {rate}, {s}, {l}, {modes!r},")
        for k in range(0, len(b64), 96):
            lines.append(f"        {b64[k:k + 96]!r}" + ("" if k + 96 < len(b64) else "),"))
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
