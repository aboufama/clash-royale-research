/** round(sin(deg) * 1e6) for any integer degree. */
export function sin1e6(deg: number): number {
  return SIN_1E6[((deg % 360) + 360) % 360];
}

/** round(cos(deg) * 1e6) for any integer degree. */
export function cos1e6(deg: number): number {
  return SIN_1E6[(((deg + 90) % 360) + 360) % 360];
}

